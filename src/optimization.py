import pandas as pd
import pulp
import logging

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

class EVOptimizationParameters:
    def __init__(self,
                 battery_capacity_kwh=40.0,
                 current_charge_kwh=10.0,
                 target_charge_kwh=35.0,
                 max_charger_power_kw=7.0,
                 charging_efficiency=0.9,
                 grid_emission_factor_kg_per_kwh=0.82):
        self.battery_capacity = battery_capacity_kwh
        self.current_charge = current_charge_kwh
        self.target_charge = target_charge_kwh
        self.max_power = max_charger_power_kw
        self.efficiency = charging_efficiency
        # Indian Grid typical emission factor (0.82 kg CO2 / kWh)
        self.grid_emission_factor = grid_emission_factor_kg_per_kwh

        # Energy required from the grid (accounting for efficiency loss)
        self.energy_needed = (self.target_charge - self.current_charge) / self.efficiency


def optimize_charging(forecast_df, ev_params: EVOptimizationParameters, start_hour_idx=0, hours_available=12):
    """
    Simulates scheduling over a given window based on solar forecasts and grid constraints.
    Returns scheduling for three strategies: Immediate, Cheapest-Time, Carbon-Aware.
    """
    # Ensure window is valid
    end_hour_idx = min(start_hour_idx + hours_available, len(forecast_df))
    window_df = forecast_df.iloc[start_hour_idx:end_hour_idx].copy()
    actual_hours_available = len(window_df)

    if ev_params.energy_needed > (actual_hours_available * ev_params.max_power):
        logger.warning("Target charge is infeasible in the given timeframe.")
        return {"status": "Infeasible", "message": "Not enough time to reach target charge."}

    # Extract time series data
    timestamps = window_df['DATE_TIME'].dt.strftime('%H:%M').tolist()
    solar_forecast = window_df['PREDICTED_AC_POWER'].values  # kW generated by plant

    # ---------------------------------------------------------
    # Assumption & Simplification for Local Carbon Calculation:
    # ---------------------------------------------------------
    # The dataset provides gross solar AC power generated (often in thousands of kW).
    # We define a "Carbon Intensity Factor" for each hour.
    # If solar generation is high, we assume more renewable energy is integrated locally,
    # lowering the effective grid emission factor linearly.
    # (0 solar = 100% grid emission, Max solar = 0% grid emission factor)

    max_solar = solar_forecast.max() if solar_forecast.max() > 0 else 1.0
    normalized_solar = solar_forecast / max_solar

    # Effective emission factor (kg CO2 / kWh) per hour
    # Higher solar output -> lower emission factor
    effective_emission_factors = ev_params.grid_emission_factor * (1.0 - normalized_solar)

    # ---------------------------------------------------------
    # Cost Assumption (Time of Use Tariff)
    # ---------------------------------------------------------
    # Off-peak: 10 PM (22:00) to 6 AM (06:00) -> 5 Rs/kWh
    # Peak: 6 AM to 10 PM -> 8 Rs/kWh
    hours = window_df['DATE_TIME'].dt.hour.values
    tariffs = [5 if (h >= 22 or h < 6) else 8 for h in hours]

    # --- Strategy 1: Immediate Charging ---
    immediate_schedule = [0.0] * actual_hours_available
    energy_left = ev_params.energy_needed
    for i in range(actual_hours_available):
        if energy_left > 0:
            charge = min(ev_params.max_power, energy_left)
            immediate_schedule[i] = charge
            energy_left -= charge

    # --- Strategy 2: Cheapest-Time Charging ---
    # PuLP Optimization for Cost
    prob_cost = pulp.LpProblem("Minimize_Cost", pulp.LpMinimize)
    charge_vars_cost = [pulp.LpVariable(f"charge_{i}", lowBound=0, upBound=ev_params.max_power) for i in range(actual_hours_available)]

    # Objective: Minimize total cost
    prob_cost += pulp.lpSum(charge_vars_cost[i] * tariffs[i] for i in range(actual_hours_available))

    # Constraint: Meet energy needed
    prob_cost += pulp.lpSum(charge_vars_cost[i] for i in range(actual_hours_available)) == ev_params.energy_needed

    prob_cost.solve(pulp.PULP_CBC_CMD(msg=0))
    cheapest_schedule = [v.varValue for v in charge_vars_cost] if prob_cost.status == pulp.LpStatusOptimal else [0.0] * actual_hours_available

    # --- Strategy 3: Carbon-Aware Charging ---
    # PuLP Optimization for Carbon
    prob_carbon = pulp.LpProblem("Minimize_Carbon", pulp.LpMinimize)
    charge_vars_carbon = [pulp.LpVariable(f"charge_{i}", lowBound=0, upBound=ev_params.max_power) for i in range(actual_hours_available)]

    # Objective: Minimize total emissions
    prob_carbon += pulp.lpSum(charge_vars_carbon[i] * effective_emission_factors[i] for i in range(actual_hours_available))

    # Constraint: Meet energy needed
    prob_carbon += pulp.lpSum(charge_vars_carbon[i] for i in range(actual_hours_available)) == ev_params.energy_needed

    prob_carbon.solve(pulp.PULP_CBC_CMD(msg=0))
    carbon_schedule = [v.varValue for v in charge_vars_carbon] if prob_carbon.status == pulp.LpStatusOptimal else [0.0] * actual_hours_available

    # ---------------------------------------------------------
    # Metrics Calculation
    # ---------------------------------------------------------
    def calc_metrics(schedule):
        cost = sum(s * t for s, t in zip(schedule, tariffs))
        emissions = sum(s * e for s, e in zip(schedule, effective_emission_factors))
        return cost, emissions

    imm_cost, imm_emissions = calc_metrics(immediate_schedule)
    cheap_cost, cheap_emissions = calc_metrics(cheapest_schedule)
    carb_cost, carb_emissions = calc_metrics(carbon_schedule)

    return {
        "status": "Optimal",
        "timestamps": timestamps,
        "solar_forecast": solar_forecast.tolist(),
        "effective_emissions": effective_emission_factors.tolist(),
        "tariffs": tariffs,
        "schedules": {
            "Immediate": immediate_schedule,
            "Cheapest": cheapest_schedule,
            "Carbon_Aware": carbon_schedule
        },
        "metrics": {
            "Immediate": {"cost_rs": imm_cost, "emissions_kg": imm_emissions},
            "Cheapest": {"cost_rs": cheap_cost, "emissions_kg": cheap_emissions},
            "Carbon_Aware": {"cost_rs": carb_cost, "emissions_kg": carb_emissions}
        }
    }

